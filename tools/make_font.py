"""Generates port/hk/font_data.h: 1-bit bitmap fonts standing in for "MS Sans Serif" (GDI text in HDKWIN.EXE).

HDKWIN.EXE asks for MS Sans Serif with LOGFONT heights 14 and 18 (cell heights). Glyphs are rendered from
Liberation Sans (SIL Open Font License 1.1) with Pillow, thresholded to 1 bit so text keeps exact palette
indices in 8-bit surfaces. Characters 0x20-0xFF are taken as Windows-1252.

Usage: python3 tools/make_font.py [path/to/LiberationSans-Regular.ttf]
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/liberation/LiberationSans-Regular.ttf"
CELLS = [14, 18]
THRESHOLD = 110


def pick_size(cell):
    """Largest point size whose ascent + descent fits the requested cell height."""
    best = 6
    for size in range(6, 40):
        a, d = ImageFont.truetype(TTF, size).getmetrics()
        if a + d <= cell:
            best = size
    return best


out = ["// Generated by tools/make_font.py from Liberation Sans Regular (SIL Open Font License 1.1).",
       "// 1-bit glyphs for characters 0x20-0xFF (Windows-1252). Do not edit by hand.",
       "#pragma once", "#include <stdint.h>", "",
       "typedef struct { uint8_t advance, width; uint16_t offset; } HkGlyph;",
       "typedef struct { int cell, ascent; const HkGlyph *glyphs; const uint32_t *rows; } HkFont;", ""]
for cell in CELLS:
    size = pick_size(cell)
    font = ImageFont.truetype(TTF, size)
    ascent, descent = font.getmetrics()
    glyphs, rows = [], []
    for code in range(0x20, 0x100):
        ch = bytes([code]).decode("cp1252", errors="replace")
        advance = max(1, round(font.getlength(ch)))
        width = min(32, advance + 2)
        img = Image.new("L", (width, cell), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        glyphs.append((advance, width, len(rows)))
        for y in range(cell):
            bits = 0
            for x in range(width):
                if img.getpixel((x, y)) >= THRESHOLD:
                    bits |= 1 << x
            rows.append(bits)
    out.append(f"// cell {cell}: Liberation Sans {size} px, ascent {ascent}")
    out.append(f"static const HkGlyph hk_glyphs_{cell}[224] = {{")
    out += [f"  {{{a}, {w}, {o}}}," for a, w, o in glyphs]
    out.append("};")
    out.append(f"static const uint32_t hk_rows_{cell}[{len(rows)}] = {{")
    for i in range(0, len(rows), 12):
        out.append("  " + ", ".join(f"0x{r:x}u" for r in rows[i:i + 12]) + ",")
    out.append("};")
    out.append("")
out.append("static const HkFont hk_fonts[] = {")
for cell in CELLS:
    size = pick_size(cell)
    ascent = ImageFont.truetype(TTF, size).getmetrics()[0]
    out.append(f"  {{{cell}, {ascent}, hk_glyphs_{cell}, hk_rows_{cell}}},")
out.append("};")
(ROOT / "port" / "hk" / "font_data.h").write_text("\n".join(out) + "\n")
print("wrote port/hk/font_data.h:", ", ".join(f"cell {c} -> {pick_size(c)} px" for c in CELLS))
