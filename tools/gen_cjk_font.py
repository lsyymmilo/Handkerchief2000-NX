import json
import os
from PIL import Image, ImageDraw, ImageFont

CHARS = json.load(open(r"C:\hdk2000-nx\.temp\cjk_chars.json", encoding="utf-8"))
FONT = r"C:\Windows\Fonts\simsun.ttc"
CELLS = [14, 18]

def render(ch, px, cell):
    f = ImageFont.truetype(FONT, px, index=0)
    img = Image.new("L", (px * 2, px * 3), 0)
    d = ImageDraw.Draw(img)
    d.text((px // 2, px), ch, font=f, fill=255)
    bbox = img.getbbox()
    if not bbox:
        return [0] * cell
    g = img.crop(bbox)
    w, h = g.size
    if w > cell:
        g = g.crop((0, 0, cell, h)); w = cell
    if h > cell:
        g = g.crop((0, 0, w, cell)); h = cell
    # bottom-aligned, horizontally centred inside the cell
    ox = (cell - w) // 2
    oy = cell - h
    rows = [0] * cell
    px_data = g.load()
    for y in range(h):
        bits = 0
        for x in range(w):
            if px_data[x, y] >= 110:
                bits |= 1 << (ox + x)
        rows[oy + y] = bits
    return rows

L = []
A = L.append
A("// Generated by gen_cjk_font.py from SimSun (a rasterised bitmap of the character set used by the game's")
A("// resources). Full-width CJK glyphs for the port's own dialog/menu UI. Do not edit by hand.")
A("#pragma once")
A("#include <stdint.h>")
A("")
A("typedef struct { uint16_t code, idx; } HkCjkGlyph;   // code = GBK lead | trail << 8, idx = glyph index (row = idx * cell)")
A("typedef struct { int cell; const HkCjkGlyph *glyphs; const uint32_t *rows; int n; } HkCjkFont;")
A("")

codes = []
charset = set()
# GB2312 (7445 characters: symbols + level 1/2 hanzi) - enough for any text the game could conceivably show
for hi in range(0xA1, 0xF8):
    for lo in range(0xA1, 0xFF):
        try:
            s = bytes([hi, lo]).decode("gb2312")
        except Exception:
            continue
        if len(s) == 1:
            charset.add(s)
# plus every character the game's RT_STRING/RT_MENU/RT_DIALOG resources actually use
for cp in CHARS:
    charset.add(chr(cp) if isinstance(cp, int) else cp)
print("charset:", len(charset))

for ch in sorted(charset):
    try:
        b = ch.encode("gbk")
    except UnicodeEncodeError:
        continue
    if len(b) == 2:
        codes.append((b[0] | (b[1] << 8), ch))
codes.sort()
print("glyphs:", len(codes))

for cell in CELLS:
    px = cell
    rows_all = []
    glyphs = []
    for i, (code, ch) in enumerate(codes):
        r = render(ch, px, cell)
        glyphs.append((code, i))
        rows_all.extend(r)
    A("static const uint32_t hk_cjk_rows_%d[] = {" % cell)
    buf = []
    for v in rows_all:
        buf.append("0x%X" % v)
        if len(buf) == 10:
            A("    " + ",".join(buf) + ",")
            buf = []
    if buf:
        A("    " + ",".join(buf) + ",")
    A("};")
    A("static const HkCjkGlyph hk_cjk_glyphs_%d[] = {" % cell)
    buf = []
    for code, off in glyphs:
        buf.append("{0x%04X,%d}" % (code, off))
        if len(buf) == 8:
            A("    " + ",".join(buf) + ",")
            buf = []
    if buf:
        A("    " + ",".join(buf) + ",")
    A("};")
    A("")

A("static const HkCjkFont hk_cjk_fonts[] = {")
for cell in CELLS:
    A("    {%d, hk_cjk_glyphs_%d, hk_cjk_rows_%d, %d}," % (cell, cell, cell, len(codes)))
A("};")
A("")
A("// Closest full-width CJK font to the requested cell height.")
A("static inline const HkCjkFont *hk_cjk_font(int cell) {")
A("    const HkCjkFont *best = &hk_cjk_fonts[0];")
A("    for (unsigned i = 1; i < sizeof hk_cjk_fonts / sizeof hk_cjk_fonts[0]; i++) {")
A("        int d = hk_cjk_fonts[i].cell - cell, b = best->cell - cell;")
A("        if ((d < 0 ? -d : d) < (b < 0 ? -b : b)) best = &hk_cjk_fonts[i];")
A("    }")
A("    return best;")
A("}")
A("")
A("// Glyph for a GBK code (lead | trail << 8); 0 when the character has no bitmap (renders as the ASCII '?').")
A("static inline const HkCjkGlyph *hk_cjk_lookup(const HkCjkFont *f, unsigned code) {")
A("    int lo = 0, hi = f->n - 1;")
A("    while (lo <= hi) {")
A("        int mid = (lo + hi) >> 1;")
A("        unsigned c = f->glyphs[mid].code;")
A("        if (c < code) lo = mid + 1; else if (c > code) hi = mid - 1; else return &f->glyphs[mid];")
A("    }")
A("    return 0;")
A("}")
A("")
A("// True for a GBK lead byte (a two-byte character starts here).")
A("static inline int hk_gbk_lead(uint8_t c) { return c >= 0x81; }")

dst = r"C:\hdk2000-nx\hk\port\hk\cjk_font_data.h"
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
