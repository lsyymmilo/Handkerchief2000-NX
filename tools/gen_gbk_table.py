import os

# Forward: Unicode (BMP) -> GBK bytes (lead | trail<<8)
pairs = {}
# Reverse: [lead-0x81][trail-0x40] -> Unicode
rev = [[0] * 191 for _ in range(126)]
for hi in range(0x81, 0xFF):
    for lo in list(range(0x40, 0x7F)) + list(range(0x80, 0xFF)):
        b = bytes([hi, lo])
        try:
            s = b.decode('gbk')
        except Exception:
            continue
        if len(s) != 1:
            continue
        u = ord(s)
        if u < 0x80 or 0xD800 <= u <= 0xDFFF:
            continue
        pairs.setdefault(u, hi | (lo << 8))
        rev[hi - 0x81][lo - 0x40] = u

items = sorted(pairs.items())

L = []
A = L.append
A('// Generated by gen_gbk_table.py - do not edit. Unicode (BMP) <-> GBK (CP936) mapping tables.')
A('// The forward table (Unicode -> GBK) is a sorted array searched by bisection; the reverse table is indexed by')
A('// [lead-0x81][trail-0x40]. Together they reproduce a Chinese-edition Windows ANSI code page conversion.')
A('#include "gbk_table.h"')
A('')
A('typedef struct { unsigned short u, g; } GbkPair;')
A('static const GbkPair g_gbk_map[] = {')
row = []
for u, g in items:
    row.append('{0x%04X,0x%04X}' % (u, g))
    if len(row) == 6:
        A('    ' + ','.join(row) + ',')
        row = []
if row:
    A('    ' + ','.join(row) + ',')
A('};')
A('')
A('static const unsigned short g_gbk_rev[126][191] = {')
for i, r in enumerate(rev):
    A('    {' + ','.join('0x%04X' % v for v in r) + '}, // lead 0x%02X' % (0x81 + i))
A('};')
A('')
A('static const unsigned short *gbk_lookup(unsigned u) {')
A('    unsigned lo = 0, hi = (unsigned)(sizeof g_gbk_map / sizeof g_gbk_map[0]);')
A('    while (lo < hi) {')
A('        unsigned mid = (lo + hi) >> 1;')
A('        if (g_gbk_map[mid].u < u) lo = mid + 1; else hi = mid;')
A('    }')
A('    if (lo < (unsigned)(sizeof g_gbk_map / sizeof g_gbk_map[0]) && g_gbk_map[lo].u == u)')
A('        return &g_gbk_map[lo].g;')
A('    return 0;')
A('}')
A('')
A('// One code point to GBK: returns 1 or 2, or 1 and writes \'?\' when GBK cannot represent it (which is what')
A('// Chinese-edition Windows does with its ANSI code page).')
A('int w32_uni_to_gbk(unsigned u, char out[2]) {')
A('    if (u < 0x80) { out[0] = (char)u; return 1; }')
A('    const unsigned short *g = gbk_lookup(u);')
A('    if (!g) { out[0] = \'?\'; return 1; }')
A('    out[0] = (char)(*g & 0xFF);')
A('    out[1] = (char)(*g >> 8);')
A('    return 2;')
A('}')
A('')
A('// NUL-terminated UTF-16 -> GBK into `out`, at most cap-1 bytes plus NUL; returns bytes written. A two-byte')
A('// character that does not fit is replaced by \'?\' so the output never ends in half a character.')
A('int w32_utf16_to_gbk(const unsigned short *w, char *out, int cap) {')
A('    int n = 0;')
A('    if (cap <= 0) return 0;')
A('    for (; *w; w++) {')
A('        char b[2];')
A('        int k = w32_uni_to_gbk(*w, b);')
A('        if (n + k > cap - 1) { out[n++] = \'?\'; break; }')
A('        out[n++] = b[0];')
A('        if (k == 2) out[n++] = b[1];')
A('    }')
A('    out[n] = 0;')
A('    return n;')
A('}')
A('')
A('// GBK two-byte character -> Unicode code point; 0 when the pair is not valid GBK.')
A('unsigned w32_gbk_to_uni(unsigned lead, unsigned trail) {')
A('    if (lead < 0x81 || lead > 0xFE || trail < 0x40 || trail == 0x7F || trail > 0xFE) return 0;')
A('    return g_gbk_rev[lead - 0x81][trail - 0x40];')
A('}')

